"""Дата окончания, которую бот отправляет в панель.

Отдельным модулем без зависимостей: правило нужно и сервису подписок, и
мониторингу, а кольцевые импорты между ними уже стоили отдельной починки.
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta


#: Панель не принимает дату в прошлом, поэтому создаваемому аккаунту, у которого
#: подписка уже истекла, ставим минимально допустимое будущее.
_MINIMUM_FUTURE = timedelta(minutes=1)


def panel_expire_at(
    end_date: datetime,
    *,
    is_active: bool,
    creating: bool,
    now: datetime | None = None,
) -> datetime | None:
    """Что положить в ``expireAt`` панели. ``None`` — не отправлять поле вовсе.

    Живой подписке идёт её настоящая дата окончания.

    Истёкшей при ОБНОВЛЕНИИ поле не отправляется. Раньше туда уходило «сейчас
    плюс минута», и панель после каждой синхронизации показывала «истекла минуту
    назад»: настоящая дата окончания затиралась, история терялась, а оператор не
    мог понять, когда подписка на самом деле закончилась. Доступ и без того
    закрыт статусом DISABLED, дата на него не влияет. Не отправляя поле, мы
    оставляем в панели ту дату, которую сами же и записали, пока подписка была
    живой, — то есть настоящую.

    При СОЗДАНИИ пропустить поле нельзя: у нового аккаунта его просто нет, а
    прошедшую дату панель не примет. Там остаётся минимально допустимое будущее.
    """
    if is_active:
        return end_date
    if not creating:
        return None
    moment = now or datetime.now(UTC)
    return max(end_date, moment + _MINIMUM_FUTURE)
